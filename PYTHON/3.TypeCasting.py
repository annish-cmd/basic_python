'''
Typecasting is the conversion of One data Type to Another Data Type.

Types:

1. Explict Conversion:
        Conversion done by the developer or programmer manually.   Eg:  String -> int

 2. Implict Conversion:
        Conversion done by the Python itself automaticaly. Eg:  Int -> float

'''

# Explict typeCasting
print("---Example of the Explict TypeCasting---")

a = "1"
b = 3

c = int(a)
print(b + c)

print("-----End of the Explict TypeCasting ---")




#Implict typeCasting
print("------Example of the implict TypeCasting----")

d = 3.09
e = 1

print(d + e)

print('----End of the Implict typeCasting---')